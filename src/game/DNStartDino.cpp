struct Hinoko {
    unsigned char active;
    Vec3f pos[2];
    Vec3f dir[2];
    clNormal3D *model;
    HSD_JObj *joints[3];
    Ember embers[20];
    int cooldown;
    int rnd;

    Hinoko();
    ~Hinoko() {
        if (model) {
            delete model;
            model = 0;
        }
    }
    void SetPos(const Vec3f *p) {
        pos[0].x = p[0].x;
        pos[0].y = p[0].y;
        pos[0].z = p[0].z;
        pos[1].x = p[1].x;
        pos[1].y = p[1].y;
        pos[1].z = p[1].z;
    }
    void SetDir(const Vec3f *d) {
        dir[0].x = d[0].x;
        dir[0].y = d[0].y;
        dir[0].z = d[0].z;
        dir[1].x = d[1].x;
        dir[1].y = d[1].y;
        dir[1].z = d[1].z;
    }
    float Rand() {
        if (++rnd >= 64) {
            rnd = 0;
        }
        return lbl_80495994[rnd];
    }
    void Spawn();
    void Update();
};

