extern "C" u8 card_unpack_legacy_dispatch(u8 *dest, const void *raw, u8 publish)
{
#ifdef __MWERKS__
    /* The code addresses the messages from the start of CardSaveData_Parser's
     * .rodata: they are lbl_803175A0, the first object of the next unit. */
    const char *messages = CardSaveData_Parser_rodata_80315378;
#else
    const char *messages = lbl_803175A0 - 0x2228;
#endif
    u8 result;
    int version;
    CardBitpack *pack;
    u8 copy[0x45];

    DebugPrintf(messages + 0x2228);
    if (raw == 0) {
        DebugPrintf(messages + 0x224C);
        return 0;
    }
    result = 0;
    memcpy(copy, raw, 0x45);
    version = Card_VerifyChecksum(dest, copy);
    if (version < 0) return 0;
    memcpy(copy, raw, 0x45);
    if (version >= 0) {
      if (version == 0) {
        pack = new CardBitpack(card_unpack_legacy_dispatch_data_803FED70, 0x37, copy, 0);
        if (bitpack_get_used_bytes(pack) <= 0x45)
            result = card_unpack_v1(dest, pack, publish);
        dest[0x16C] = 0;
        if (publish == 1) g_playerData[0x1A0] = 1;
      } else if (version == 1) {
        pack = new CardBitpack(card_unpack_legacy_dispatch_data_803FF0E0, 0x40, copy, 0);
        if (bitpack_get_used_bytes(pack) <= 0x45)
            result = CardSaveData_Parser(dest, pack, publish);
      } else {
        DebugPrintf(messages + 0x225C);
        return 0;
      }
    } else {
        DebugPrintf(messages + 0x225C);
        return 0;
    }
    DebugPrintf(messages + 0x226C, bitpack_get_used_bytes(pack),
                bitpack_get_used_bits(pack), 0x228 - bitpack_get_used_bits(pack));
    /* The original overflow path returns before releasing pack. */
    if (bitpack_get_used_bytes(pack) > 0x45) return 0;
    MemoryManager_TimedFree(pack);
    if (publish == 1 && result == 1) {
        dest[0x17E] = 1;
        lbl_806D12AF = *(int *)(dest + 0x40) >= 1;
        SetCardVolumeFlagByte(dest[0x17E]);
    }
    return result;
}
