#!/usr/bin/env python3
"""List near misses whose instructions are identical to the target and whose only
difference is a relocation (symbol or addend).

These are usually not code problems: objdiff compares `lbl_X+0x30` (target, one
unsplit pool symbol in symbols.txt) with `localTable+0` (ours).  Splitting the
pool symbol at the offsets the target uses (6cbe52d8: 11 functions 99.x -> 100)
or giving the source object the target's boundaries fixes them without touching
the code.  The other shape, `...data.0+N` vs `lbl_Y`, is §40 / pool ownership.

Usage (after ninja):  python3 tools/reloc_only_detect.py [--min 90] [--md docs/sweeps/reloc_only.md]
"""
import argparse, collections, json, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OBJDUMP = ROOT / 'build/binutils/powerpc-eabi-objdump'
MASK = {'R_PPC_ADDR16_LO': 0xFFFF0000, 'R_PPC_ADDR16_HA': 0xFFFF0000, 'R_PPC_ADDR16_HI': 0xFFFF0000,
        'R_PPC_REL24': 0xFC000003, 'R_PPC_REL14': 0xFFFF0003, 'R_PPC_EMB_SDA21': 0xFFE00000,
        'R_PPC_ADDR32': 0}
HDR = re.compile(r'^[0-9a-f]+ <(.+)>:$')
INS = re.compile(r'^\s*([0-9a-f]+):\t((?:[0-9a-f]{2} ){4})')
REL = re.compile(r'^\s*([0-9a-f]+): (R_PPC_\S+)\s+(.+)$')


def funcs(obj):
    out = subprocess.run([str(OBJDUMP), '-dr', '-j', '.text', str(obj)], capture_output=True, text=True).stdout
    res, cur = {}, None
    for l in out.splitlines():
        m = HDR.match(l)
        if m:
            cur = res.setdefault(m.group(1), [])
            continue
        if cur is None:
            continue
        m = INS.match(l)
        if m:
            cur.append([int(m.group(2).replace(' ', ''), 16), None])
            continue
        m = REL.match(l)
        if m and cur:
            cur[-1][1] = (m.group(2), m.group(3).strip())
    return res


def split_sym(s):
    m = re.match(r'^(.*?)([+-]0x[0-9a-f]+)?$', s)
    return m.group(1), int(m.group(2) or '0', 16)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--min', type=float, default=90.0)
    ap.add_argument('--md')
    a = ap.parse_args()
    rep = json.loads((ROOT / 'build/GNLJ82/report.json').read_text())
    rows = []
    for u in rep['units']:
        near = [f for f in u.get('functions', []) if a.min <= f.get('fuzzy_match_percent', 0) < 100]
        if not near:
            continue
        name = u['name'].split('/', 1)[1]
        ours, tgt = ROOT / f'build/GNLJ82/src/{name}.o', ROOT / f'build/GNLJ82/obj/{name}.o'
        if not ours.exists() or not tgt.exists():
            continue
        fo, ft = funcs(ours), funcs(tgt)
        for f in near:
            o, t = fo.get(f['name']), ft.get(f['name'])
            if not o or not t or len(o) != len(t):
                continue
            diffs, same = [], True
            for (wo, ro), (wt, rt) in zip(o, t):
                ty = (rt or ro or (None,))[0]
                mask = MASK.get(ty, 0xFFFFFFFF)
                if (ro is None) != (rt is None) or (ro and rt and ro[0] != rt[0]) or (wo & mask) != (wt & mask):
                    same = False
                    break
                if ro and ro != rt and ty != 'R_PPC_REL24':
                    diffs.append((rt[1], ro[1]))
                elif ro and ro != rt:
                    diffs.append((rt[1], ro[1]))
            if same and diffs:
                rows.append((name, f['name'], f['fuzzy_match_percent'], diffs))
    rows.sort(key=lambda r: (r[0], r[1]))
    out = ['# Near misses that differ from the target only in relocations', '',
           f'{len(rows)} functions (>= {a.min}%). Generated by tools/reloc_only_detect.py.', '',
           'Fix by splitting the target pool symbol in symbols.txt at the listed offsets (target `lbl+N` vs our own',
           'object) or by giving our object the target boundaries; `...data.0+N` on our side means the anchor',
           'is used where the target names the object (pool ownership / §40).', '']
    for name, fn, pct, diffs in rows:
        out.append(f'## {fn} ({pct:.2f}) `{name}`')
        seen = collections.OrderedDict()
        for t, o in diffs:
            seen[(t, o)] = seen.get((t, o), 0) + 1
        splits = sorted({split_sym(t) for t, _ in seen if split_sym(t)[1]})
        for (t, o), n in seen.items():
            out.append(f'- target `{t}` / ours `{o}` x{n}')
        if splits:
            out.append('- split candidates: ' + ', '.join(f'`{s}+0x{off:X}`' for s, off in splits))
        out.append('')
    text = '\n'.join(out)
    if a.md:
        Path(a.md).write_text(text)
        print(f'{len(rows)} functions -> {a.md}')
    else:
        print(text)


if __name__ == '__main__':
    main()
