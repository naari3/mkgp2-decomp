# features of one near miss

EDIT = re.compile(r"^(create|keep|swap|drop|add|forbid|phantom|merge|renumber)\b(.*)$")


def regfix_features(row: dict) -> list[dict]:
    """regfix results row -> [{edit, x_kind, x_def}, ...] one per suggested edit."""
    feats = []
    for alt in row.get("edits") or []:
        for s in alt:
            m = EDIT.match(s)
            if not m:
                continue
            kind = m.group(1)
            rest = m.group(2)
            if kind == "create":
                kind += "_after" if re.search(r"\)\s+after\s+r\d+", s) else "_before"
            xm = re.search(r"r\d+\((temp|param)?", s)
            xk = (xm.group(1) if xm and xm.group(1) else "local") if xm else "?"
            dm = re.search(r"def line[^`]*`([^`]*)`", s)
            feats.append({"edit": kind, "x_kind": xk, "x_def": dm.group(1) if dm else "", "text": s})
    return feats


class Fn:
    """Everything the rule predicates look at for one function."""

    def __init__(self, unit: str, fn: str, census: dict | None, regfix: dict | None):
        self.unit, self.fn, self.census, self.regfix = unit, fn, census, regfix
        self._asm = None
        self._src = None

    @property
    def asm(self):
        if self._asm is None:
            p = asmgrep.ASM / (self.unit + ".s")
            self._asm = asmgrep.parse_asm_file(p).get(self.fn, []) if p.exists() else []
        return self._asm

    @property
    def src(self):
        if self._src is None:
            s = (self.census or {}).get("src")
            cands = [ROOT / s] if s else [ROOT / "src" / (self.unit + e) for e in (".c", ".cpp", ".cp")]
            self._src = next((c.read_text(errors="replace") for c in cands if c.exists()), "")
        return self._src


def holds(alt: dict, f: Fn) -> bool:
    for key, cond in alt.items():
        if key == "census":
            if not f.census:
                return False
            for fld, vals in cond.items():
                if f.census.get(fld) not in vals:
                    return False
        elif key == "regfix":
            feats = regfix_features(f.regfix or {})
            ok = False
            for ft in feats:
                if "edit" in cond and ft["edit"] not in cond["edit"]:
                    continue
                if "x_kind" in cond and ft["x_kind"] not in cond["x_kind"]:
                    continue
                if "x_def" in cond and not re.search(cond["x_def"], ft["x_def"]):
                    continue
                ok = True
                break
            if not ok:
                return False
        elif key == "asm_target":
            if not f.asm:
                return False
            pat = asmgrep.Pat(cond)
            items = pat.items
            if not any(next(asmgrep.match_at(items, f.asm, i), None) for i in range(len(f.asm))):
                return False
        elif key == "src_re":
            if not re.search(cond, f.src):
                return False
        else:
            return False
    return True


SPECIFIC = {"asm_target": 3, "regfix": 2, "src_re": 2, "census": 1}


def match_rules(rules, f: Fn, weights):
    """[(score, rule, matched_alt)] best first. Score = specificity of the
    matched alternative + log-ish weight from evidence and recorded hits."""
    out = []
    for r in rules:
        best = None
        for alt in r.get("when", []):
            if holds(alt, f):
                s = sum(SPECIFIC.get(k, 0) for k in alt) + (len(alt.get("census", {})) - 1) * 0.25 \
                    if "census" in alt else sum(SPECIFIC.get(k, 0) for k in alt)
                if best is None or s > best[0]:
                    best = (s, alt)
        if best:
            w = weights.get(r["id"], 0)
            out.append((best[0] + min(2.0, w / 10.0), r, best[1]))
    out.sort(key=lambda x: -x[0])
    return out


def rule_weights():
    w = collections.Counter()
    for e in load_jsonl(EVIDENCE):
        w[e.get("rule")] += 1
    for h in load_hits():
        w[h.get("rule_id")] += {"landed": 3, "match": 3, "improved": 1}.get(h.get("outcome"), 0)
    return w


def near_misses(census_path: Path, regfix_path: Path, min_pct: float):
    census = {}
    if census_path.exists():
        for c in json.loads(census_path.read_text()):
            census[(asmgrep.unit_key(c["unit"]), c["fn"])] = c
    regfix = {}
    for r in load_jsonl(regfix_path):
        regfix[(r["unit"], r["fn"])] = r
    keys = set(census) | set(regfix)
    rep = asmgrep.load_report()
    pct = {}
    for u in rep.get("units", []):
        for fn in u.get("functions", []):
            p = fn.get("fuzzy_match_percent", 0)
            if min_pct <= p < 100.0:
                pct[(asmgrep.unit_key(u["name"]), fn["name"])] = p
    keys = {k for k in keys if k in pct}
    return [(Fn(u, f, census.get((u, f)), regfix.get((u, f))), pct[(u, f)]) for u, f in sorted(keys)], len(pct)


