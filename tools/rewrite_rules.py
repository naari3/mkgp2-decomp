#!/usr/bin/env python3
"""rewrite_rules.py: the machine-readable catalog of "target shape -> source
rewrite" rules, matched against the current near misses.

Files
  tools/patterns/rules.jsonl     the rules (hand-curated, one JSON per line)
  tools/patterns/evidence.jsonl  functions each rule fixed (generated by
                                 `import-evidence` from the rules' own
                                 evidence plus the onmokoworks Codex table in
                                 docs/regalloc_patterns.md; re-run after the
                                 table grows)
  /mnt/project-files/setup/patterns/hits.jsonl
                                 append-only log of rule applications from
                                 any tool or thread (`record`, or append the
                                 same JSON yourself). Read by `stats` and
                                 used to rank rules.

Rule fields
  id, title, category
  when      list of alternatives; a rule applies when ANY alternative holds,
            and an alternative holds when ALL its keys hold:
              census     {field: [values]} on the tools/regswap_classify.py
                         signature (family, kind, shape, where, value)
              regfix     {edit: [create_after|create_before|keep|swap],
                          x_kind: [temp|local|param], x_def: regex on the
                          defining PCode} on a row of regfix results.jsonl
              asm_target asmgrep pattern lines found in the TARGET function
              src_re     regex found in the function's TU source
  rewrite   {kind, template, description}; kind is one of
            pragma | compiler | reorder_decl | hoist_to_local | split_init |
            unvar | inline_wrap | inline_expand | loop_shape | reorder_stmt |
            type_change | data_owner | other
  tool      command that automates the rule, when one exists
  evidence  [{fn, commit}], refs [docs anchors]

Commands
  python3 -I tools/rewrite_rules.py coverage [--census F] [--regfix F] [--md OUT] [--min 90]
  python3 -I tools/rewrite_rules.py suggest UNIT FN       ranked rules for one near miss
  python3 -I tools/rewrite_rules.py record --fn FN --unit UNIT --rule ID --tool T
                                     [--before S --after S] [--commit C] [--note N]
  python3 -I tools/rewrite_rules.py report [--md OUT]   convergence: what is left, reuse vs new, outcomes
  python3 -I tools/rewrite_rules.py import-evidence

The census is build/regswap_census.json (`python3 -I tools/regswap_classify.py
--min 90 --json build/regswap_census.json`); regfix results default to
/mnt/project-files/setup/regfix/results.jsonl.
"""
