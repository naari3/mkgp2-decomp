def cmd_coverage(a):
    rules = load_rules()
    w = rule_weights()
    fns, n_total = near_misses(Path(a.census), Path(a.regfix), a.min)
    per_rule = collections.defaultdict(list)
    per_fn = {}
    for f, p in fns:
        m = match_rules(rules, f, w)
        per_fn[(f.unit, f.fn)] = (p, m)
        for s, r, alt in m:
            per_rule[r["id"]].append((f, s, alt))
    ev = collections.Counter(e.get("rule") for e in load_jsonl(EVIDENCE))
    hits = collections.Counter(h.get("rule_id") for h in load_hits())
    covered = sum(1 for p, m in per_fn.values() if m)
    specific = sum(1 for p, m in per_fn.values() if any(set(alt) - {"census"} for _, _, alt in m))
    lines = [
        "# Rewrite-rule coverage of the current near misses",
        "",
        f"Generated by `python3 -I tools/rewrite_rules.py coverage --md {a.md or '-'}` "
        f"({dt.date.today().isoformat()}). Rules: `tools/patterns/rules.jsonl` ({len(rules)}), "
        "evidence: `tools/patterns/evidence.jsonl`, hits: `/mnt/project-files/setup/patterns/hits.jsonl`. "
        "Near misses = functions in report.json between "
        f"{a.min} and 100 % that have a register census row (tools/regswap_classify.py) or a regfix result.",
        "",
        f"- near misses in report.json at >= {a.min} %: **{n_total}**; with a census/regfix row: **{len(fns)}**",
        f"- with at least one applicable rule: **{covered}**; with a specific trigger "
        f"(asm shape, regfix diagnosis or source regex, not just the census family): **{specific}**",
        "",
        "A rule 'applies' when its trigger holds; that says the rule is worth trying, not that it will match. "
        "Census-only triggers are broad by design (they list where a lever has worked before); the "
        "asm/regfix triggers are the precise ones. `evidence` = functions the rule already fixed, `hits` = "
        "recorded applications since the log started.",
        "",
        "| rule | kind | applies to | specific | evidence | hits | automated by |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in sorted(rules, key=lambda r: -len(per_rule.get(r["id"], []))):
        lst = per_rule.get(r["id"], [])
        spec = sum(1 for _, _, alt in lst if set(alt) - {"census"})
        tool = (r.get("tool") or "").split("  ")[0]
        lines.append(f"| `{r['id']}` {r['title']} | {r['rewrite']['kind']} | {len(lst)} | {spec} | "
                     f"{ev.get(r['id'], 0)} | {hits.get(r['id'], 0)} | {('`' + tool + '`') if tool else '-'} |")
    lines += ["", "## Per function (top 3 rules, best first)", "",
              "| function | % | census | regfix | rules |", "|---|---|---|---|---|"]
    for (u, fn), (p, m) in sorted(per_fn.items(), key=lambda kv: -kv[1][0]):
        f = next(x for x, _ in fns if x.unit == u and x.fn == fn)
        c = f.census or {}
        sig = f"{c.get('family', '-')}/{c.get('kind', '-')}/{c.get('value', '-')}" if c else "-"
        rf = regfix_features(f.regfix or {})
        rfs = f"{rf[0]['edit']} {rf[0]['x_kind']}" if rf else ("-" if not f.regfix else "no edit")
        top = ", ".join(f"`{r['id']}`" + ("*" if set(alt) - {"census"} else "") for _, r, alt in m[:3])
        lines.append(f"| {fn} ({u}) | {p:.2f} | {sig} | {rfs} | {top or '-'} |")
    lines += ["", "`*` = matched by a specific trigger (asm shape / regfix diagnosis / source regex)."]
    text = "\n".join(lines) + "\n"
    if a.md:
        Path(a.md).write_text(text)
        print(f"wrote {a.md}: {len(fns)} near misses, {covered} covered, {specific} specific", file=sys.stderr)
    else:
        print(text)


def cmd_suggest(a):
    rules = load_rules()
    census = None
    cp = Path(a.census)
    if cp.exists():
        for c in json.loads(cp.read_text()):
            if c["fn"] == a.fn and asmgrep.unit_key(c["unit"]) == a.unit:
                census = c
    regfix = next((r for r in load_jsonl(Path(a.regfix)) if r["fn"] == a.fn and r["unit"] == a.unit), None)
    f = Fn(a.unit, a.fn, census, regfix)
    if not census:
        print("(no census row: only asm/regfix/source triggers are checked; run tools/regswap_classify.py)",
              file=sys.stderr)
    for s, r, alt in match_rules(rules, f, rule_weights()):
        print(f"{s:5.2f}  {r['id']:24s} {r['title']}")
        print(f"       trigger: {', '.join(alt)}   rewrite: {r['rewrite']['kind']}")
        if r.get("tool"):
            print(f"       tool: {r['tool']}")
        for l in r["rewrite"].get("template", "").splitlines():
            print("       | " + l)


# shapesweep move label prefix -> rule id
MOVE_RULES = [
    ("hoist", "temp-to-local"), ("unvar", "no-cached-pointer"), ("wrap", "inline-boundary"),
    ("getter", "inline-boundary"), ("id ", "inline-boundary"), ("expand", "inline-boundary"),
    ("swap", "expr-operand-order"), ("assoc", "expr-operand-order"), ("accum", "expr-operand-order"),
    ("setter", "stmt-order"), ("declswap", "decl-order"),
]


def rules_for_moves(moves) -> list[str]:
    out = []
    for m in moves or []:
        m = m[4:] if m.startswith("sym-") else m
        rid = next((r for p, r in MOVE_RULES if m.startswith(p)), None)
        if rid and rid not in out:
            out.append(rid)
    return out


def record_hit(fn, unit, rule_id, tool, before=None, after=None, commit=None, note=None, outcome=None):
    """Append one rule application to the shared hits log. Scores are diff
    lines (0 = match, lower is better). outcome: attempt | improved | match |
    landed (derived from the scores and commit when omitted). Never
    raises: callers are long-running sweeps."""
    try:
        if outcome is None:
            if commit:
                outcome = "landed"
            elif after == 0:
                outcome = "match"
            elif before is not None and after is not None and after < before:
                outcome = "improved"
            else:
                outcome = "attempt"
        SHARED.mkdir(parents=True, exist_ok=True)
        rec = {"ts": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"), "fn": fn, "unit": unit,
               "rule_id": rule_id, "tool": tool, "outcome": outcome, "before_score": before,
               "after_score": after, "landed_commit": commit, "note": note}
        with open(HITS, "a") as fh:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
        return True
    except Exception:  # noqa: BLE001
        return False


def record_shapesweep(rec: dict, allowed) -> None:
    """Hook for tools/shapesweep.py batch: one row per rule family it tried."""
    try:
        if rec.get("error") or rec.get("start") is None:
            return
        tried = rules_for_moves(sorted(allowed))
        won = rules_for_moves(rec.get("moves"))
        for rid in dict.fromkeys(tried + won):
            if rid in won:
                record_hit(rec["fn"], rec["obj"], rid, "shapesweep", rec["start"], rec.get("best"))
            else:
                record_hit(rec["fn"], rec["obj"], rid, "shapesweep", rec["start"], rec["start"], outcome="attempt")
    except Exception:  # noqa: BLE001
        pass


def record_autopipe(r: dict) -> None:
    """Hook for tools/autopipe.py record(): pragma / compiler / decl / stmt stages."""
    try:
        oc = r.get("outcome")
        if oc in (None, "held") or r.get("error"):
            return
        win = oc in ("hit", "landed", "perm_match")
        used = set()
        if win:
            if r.get("pragmas"):
                used.add("pragma-opt-off")
            if r.get("cc") and r.get("own_cc") and r["cc"] != r["own_cc"]:
                used.add("compiler-version")
            if r.get("order"):
                used.add("decl-order")
            if "stmt" in str(r.get("info", "")):
                used.add("stmt-order")
        tried = ["pragma-opt-off", "compiler-version", "decl-order"] + (["stmt-order"] if r.get("stmt") else [])
        base, best = r.get("base"), r.get("stage12_best")
        for rid in dict.fromkeys(tried + sorted(used)):
            if rid in used:
                outcome = "landed" if oc == "landed" else "match"
            elif rid in ("pragma-opt-off", "compiler-version") and base is not None and best is not None \
                    and best < base and ((rid == "pragma-opt-off" and r.get("pragmas"))
                                         or (rid == "compiler-version" and r.get("cc") != r.get("own_cc"))):
                outcome = "improved"
            else:
                outcome = "attempt"
            record_hit(r.get("fn"), r.get("obj"), rid, "autopipe", base, best, note=oc, outcome=outcome)
    except Exception:  # noqa: BLE001
        pass


def cmd_record(a):
    if record_hit(a.fn, a.unit, a.rule, a.tool, a.before, a.after, a.commit, a.note, a.outcome):
        print(f"recorded in {HITS}")
    else:
        sys.exit(f"could not write {HITS}")


def _commit_dates(commits):
    """{commit: YYYY-MM-DD} for the hex commit ids that exist in this clone."""
    import subprocess
    cs = sorted({c for c in commits if c and re.fullmatch(r"[0-9a-f]{7,40}", c)})
    if not cs:
        return {}
    r = subprocess.run(["git", "cat-file", "--batch-check=%(objectname) %(objecttype)"], cwd=ROOT,
                       input="\n".join(cs) + "\n", capture_output=True, text=True)
    full = {}
    for c, l in zip(cs, r.stdout.splitlines()):
        parts = l.split()
        if len(parts) == 2 and parts[1] == "commit":
            full[c] = parts[0]
    if not full:
        return {}
    r = subprocess.run(["git", "show", "-s", "--format=%H %cs"] + sorted(set(full.values())), cwd=ROOT,
                       capture_output=True, text=True)
    d = dict(l.split() for l in r.stdout.splitlines() if l.strip())
    return {c: d[h] for c, h in full.items() if h in d}


def nearmiss_snapshot(census_path: Path):
    rep = asmgrep.load_report()
    bands = collections.Counter()
    for u in rep.get("units", []):
        for fn in u.get("functions", []):
            p = fn.get("fuzzy_match_percent", 0)
            if p >= 100:
                bands["100"] += 1
            elif p >= 99:
                bands["99-100"] += 1
            elif p >= 97:
                bands["97-99"] += 1
            elif p >= 90:
                bands["90-97"] += 1
            elif p > 0:
                bands["0-90"] += 1
            else:
                bands["0"] += 1
    kinds = collections.Counter()
    claimed = collections.Counter()
    if census_path.exists():
        for c in json.loads(census_path.read_text()):
            kinds[c.get("kind")] += 1
            if c.get("claim"):
                claimed[c.get("kind")] += 1
    return {"ts": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
            "bands": dict(bands), "census_kinds": dict(kinds), "census_claimed": dict(claimed)}


def cmd_report(a):
    """Is the rule-driven approach converging? Rule outcomes over time, fixes
    reusing known rules vs new ones, and the shape of what is left."""
    rules = {r["id"]: r for r in load_rules()}
    L = []
    snap = nearmiss_snapshot(Path(a.census))
    hist_p = SHARED / "nearmiss_history.jsonl"
    hist = load_jsonl(hist_p)
    if not a.no_snapshot:
        try:
            SHARED.mkdir(parents=True, exist_ok=True)
            with open(hist_p, "a") as fh:
                fh.write(json.dumps(snap) + "\n")
            hist.append(snap)
        except OSError:
            pass
    b = snap["bands"]
    L += ["# Rewrite rules: convergence report", "",
          f"Generated by `python3 -I tools/rewrite_rules.py report` at {snap['ts']}.", "",
          "## What is left", "",
          f"Functions in report.json: 100 % **{b.get('100', 0)}**, 99-100 **{b.get('99-100', 0)}**, "
          f"97-99 **{b.get('97-99', 0)}**, 90-97 **{b.get('90-97', 0)}**, below 90 **{b.get('0-90', 0)}**, "
          f"0 % / unmatched **{b.get('0', 0)}**.", ""]
    k = snap["census_kinds"]
    if k:
        tot = sum(k.values())
        L += ["Register census of the near misses (>= the census --min; 'claimed' needs "
              "`regswap_classify.py --claims`):", "",
              "| diff kind | functions | claimed by others | meaning |", "|---|---|---|---|"]
        mean = {"reg_only": "same instructions, registers only: regfix/decl/temp rules",
                "reg+sched": "registers + order: statement/expression/const rules",
                "reg+other": "registers + immediates/relocs/opcodes: often data ownership or a different expression",
                "no_reg": "no register diff: schedule, reloc or data"}
        for kk in ("reg_only", "reg+sched", "reg+other", "no_reg"):
            L.append(f"| {kk} | {k.get(kk, 0)} ({100 * k.get(kk, 0) // max(1, tot)} %) | "
                     f"{snap['census_claimed'].get(kk, 0)} | {mean[kk]} |")
        L.append("")
    if len(hist) > 1:
        L += ["Trend (one row per report run, `nearmiss_history.jsonl`):", "",
              "| when | 100 % | 99-100 | 97-99 | 90-97 | reg_only | reg+sched | reg+other | no_reg |",
              "|---|---|---|---|---|---|---|---|---|"]
        for h in hist[-15:]:
            hb, hk = h["bands"], h.get("census_kinds", {})
            L.append(f"| {h['ts'][:16]} | {hb.get('100', 0)} | {hb.get('99-100', 0)} | {hb.get('97-99', 0)} | "
                     f"{hb.get('90-97', 0)} | {hk.get('reg_only', 0)} | {hk.get('reg+sched', 0)} | "
                     f"{hk.get('reg+other', 0)} | {hk.get('no_reg', 0)} |")
        L.append("")
    # matched-function pace from the progress-data branch (CI history)
    import subprocess
    r = subprocess.run(["git", "show", "origin/progress-data:history/GNLJ82.jsonl"], cwd=ROOT,
                       capture_output=True, text=True)
    if r.returncode == 0 and r.stdout:
        last = collections.OrderedDict()
        for l in r.stdout.splitlines():
            try:
                h = json.loads(l)
            except ValueError:
                continue
            if "matched_functions" in h:
                last[h["ts"][:10]] = h
        days = list(last.items())[-10:]
        if days:
            L += ["Pace (last CI entry per day, `origin/progress-data`; run `git fetch origin progress-data` first):", "",
                  "| day | matched fns | +day | left | true C fns | asm fns |", "|---|---|---|---|---|---|"]
            prev = None
            for d, h in days:
                m = h["matched_functions"]
                L.append(f"| {d} | {m} | {'' if prev is None else f'{m - prev:+d}'} | "
                         f"{h.get('total_functions', 0) - m} | {h.get('true_matched_functions', '-')} | "
                         f"{h.get('asm_fn_count', '-')} |")
                prev = m
            L.append("")
    # evidence over time: reuse of known rules vs new patterns
    ev = load_jsonl(EVIDENCE)
    dates = _commit_dates(sorted({e["commit"] for e in ev if e.get("commit")}))
    seen = set()
    per_day = collections.OrderedDict()
    for e in sorted(ev, key=lambda e: dates.get(e.get("commit"), "9999")):
        d = dates.get(e.get("commit"))
        if not d:
            continue
        row = per_day.setdefault(d, collections.Counter())
        rid = e.get("rule")
        if rid in (None, "unclassified"):
            row["new"] += 1
        elif rid in seen:
            row["reuse"] += 1
        else:
            row["first"] += 1
            seen.add(rid)
    L += ["## Past fixes: known rule reused, or a new pattern?", "",
          "From `tools/patterns/evidence.jsonl` by commit date. `first` = first fix of a rule that is now in "
          "the catalog, `reuse` = a later fix by an already-seen rule, `new` = fix that fits no rule yet. A "
          "converging catalog shows `reuse` growing and `new` shrinking.", "",
          "| date | fixes | first | reuse | new |", "|---|---|---|---|---|"]
    for d, c in per_day.items():
        L.append(f"| {d} | {sum(c.values())} | {c['first']} | {c['reuse']} | {c['new']} |")
    L += ["", f"({sum(1 for e in ev if not dates.get(e.get('commit')))} evidence rows have no commit date.)", ""]
    # rule outcomes from the hits log
    hits = load_hits()
    L += ["## Rule applications (hits log)", ""]
    if not hits:
        L += [f"No applications recorded yet in `{HITS}`. shapesweep batch, autopipe and regfix append there; "
              "record manual ones with `tools/rewrite_rules.py record`.", ""]
    else:
        oc = collections.defaultdict(collections.Counter)
        days = collections.defaultdict(collections.Counter)
        for h in hits:
            oc[h.get("rule_id")][h.get("outcome", "attempt")] += 1
            days[h.get("ts", "")[:10]][h.get("outcome", "attempt")] += 1
        L += ["| rule | attempts | improved | match | landed | hit rate |", "|---|---|---|---|---|---|"]
        for rid, c in sorted(oc.items(), key=lambda kv: -(kv[1]["match"] + kv[1]["landed"])):
            n = sum(c.values())
            win = c["match"] + c["landed"]
            L.append(f"| `{rid}`{'' if rid in rules else ' (unknown)'} | {n} | {c['improved']} | {c['match']} | "
                     f"{c['landed']} | {100 * win / max(1, n):.0f} % |")
        L += ["", "| day | attempts | improved | match | landed |", "|---|---|---|---|---|"]
        for d in sorted(days):
            c = days[d]
            L.append(f"| {d} | {sum(c.values())} | {c['improved']} | {c['match']} | {c['landed']} |")
        L.append("")
    text = "\n".join(L) + "\n"
    if a.md:
        Path(a.md).write_text(text)
        print(f"wrote {a.md}", file=sys.stderr)
    else:
        print(text)


ONMOKO_GROUPS = {
    "Local lifetimes": "lifetime-block-reuse",
    "Declaration order": "decl-order",
    "Literal vs extern constant": "literal-vs-extern",
    "Inline helper": "inline-boundary",
    "Types": "real-definition-type",
    "Expression form": "expr-operand-order",
    "Loop": "loop-index-shape",
    "Other": None,
}
KEYWORDS = [  # (regex on the fix text, rule) refinements inside a group
    (r"\b(long|unsigned|signed|s16|u16|short)\b.*\b(type|local)\b", "int-type-of-local"),
    (r"\bconst\b", "real-definition-type"),
    (r"\bliteral\b", "literal-vs-extern"),
    (r"return(s|ing)? .*expression|direct(ly)? return", "inline-return-expr"),
    (r"cached pointer|direct(ly)? (index|reference)", "no-cached-pointer"),
]


def cmd_import_evidence(a):
    rules = load_rules()
    ids = {r["id"] for r in rules}
    out = []
    for r in rules:
        for e in r.get("evidence", []):
            out.append({"fn": e["fn"], "commit": e.get("commit"), "rule": r["id"], "source": "rules.jsonl"})
    doc = (ROOT / "docs" / "regalloc_patterns.md").read_text()
    sec = doc.split("## onmokoworks Codex fixes", 1)
    if len(sec) == 2:
        group = None
        for l in sec[1].splitlines():
            if l.startswith("### "):
                g = l[4:]
                group = next((v for k, v in ONMOKO_GROUPS.items() if g.startswith(k)), None)
                continue
            if not l.startswith("| `"):
                continue
            cells = [c.strip() for c in l.strip().strip("|").split("|")]
            if len(cells) < 5:
                continue
            fn = cells[0].strip("`")
            fix = cells[4]
            commit = cells[5] if len(cells) > 5 and re.fullmatch(r"[0-9a-f]{7,40}", cells[5]) else None
            rule = group
            for rx, rid in KEYWORDS:
                if re.search(rx, fix, re.I) and rid in ids:
                    rule = rid
                    break
            out.append({"fn": fn, "unit": cells[1], "from_pct": cells[2], "commit": commit,
                        "rule": rule or "unclassified", "source": "regalloc_patterns.md onmokoworks table",
                        "residual": cells[3][:300], "fix": fix[:400]})
    EVIDENCE.write_text("".join(json.dumps(x, ensure_ascii=False) + "\n" for x in out))
    c = collections.Counter(x["rule"] for x in out)
    print(f"wrote {EVIDENCE.relative_to(ROOT)}: {len(out)} rows; " + ", ".join(f"{k} {v}" for k, v in c.most_common()))


